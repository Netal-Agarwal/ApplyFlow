@dataclass
class DailyResult:
    sent_day: str
    next_day: str = ""
    backup: Path | None = None
    marked: list[str] = field(default_factory=list)
    skipped: list[str] = field(default_factory=list)
    followups_marked: list[str] = field(default_factory=list)
    brake: str = ""
    batch: object = None
    rows: list[dict] = field(default_factory=list)
    batch_path: Path | None = None
    followups: list = field(default_factory=list)
    followup_skips: dict = field(default_factory=dict)
    followups_path: Path | None = None
    notes: list[str] = field(default_factory=list)


def daily(store, profile, sent_day: date, next_day: date | None = None, skip: tuple[str, ...] = (),
          skip_followups: tuple[str, ...] = (), followups: int = 10, fresh_factory=None, dnc=None,
          force: bool = False, out_dir: Path = config.OUTPUT_DIR, backup_dir: Path | None = None,
          log: Log = print) -> DailyResult:
    from applyflow.followups import next_working_day
    from applyflow.outreach import OutreachError, make_queue, mark_batch_sent
    from applyflow.sending import day_brake, sends_on
    s = sent_day.isoformat()
    res = DailyResult(sent_day=s)
    res.backup = backup(store, (backup_dir or config.DEFAULT_DB_PATH.parent) / f"applyflow.pre-daily-{s}.db")
    for tid in skip:                          # not sent after all: back into the pool
        if any(r["target_id"] == tid for r in store.queue(s)):
            store.remove_from_queue(s, tid)
            res.skipped.append(tid)
        else:
            res.notes.append(f"--skip {tid}: not in the {s} batch")
    if store.queue(s):
        try:
            res.marked = mark_batch_sent(store, profile, sent_day, dnc)
        except OutreachError as exc:
            res.notes.append(str(exc))
    else:
        res.notes.append(f"no stored batch for {s}: nothing to mark")
    done = {e["target_id"] for e in store.events() if e["event"] == "followup"}
    planned = json.loads(store.get_state(f"followups:{s}", "[]") or "[]")
    sent_ids = {e["target_id"]: (e["company_key"], e["email"]) for e in store.events() if e["event"] == "sent"}
    for tid in planned:
        if tid in skip_followups or tid in done or tid not in sent_ids:
            continue
        key, email = sent_ids[tid]
        store.add_event(tid, key, email, "followup", s, s)
        res.followups_marked.append(f"{tid} -> {email}")
    if res.followups_marked:
        from applyflow.outreach import refresh_drafts
        refresh_drafts(store, profile, dnc)
    hard = sum(1 for e in store.events() if e["event"] == "bounced" and e["event_date"] == s)
    res.brake = day_brake(hard, sends_on(store, sent_day), profile.outreach["sending"])
    if res.brake and not force:
        res.notes.append(f"daily brake on {s}: {res.brake}; no batch built (check the bounces, then rerun with "
                         "--force to build anyway)")
        return res
    nxt = next_day or next_working_day(sent_day)
    res.next_day = nxt.isoformat()
    if store.plan_rows(res.next_day):
        res.notes.append(f"{res.next_day} has engine plan rows; not touched")
        return res
    fresh = fresh_factory(nxt) if fresh_factory else None
    res.batch = make_queue(store, profile, nxt, None, dnc, fresh=fresh)
    res.rows = batch_rows(store, profile, res.next_day, dnc)
    res.batch_path = write_batch_md(res.rows, out_dir / f"batch_{res.next_day}.md", res.next_day)
    res.followups, res.followup_skips = followup_checklist(store, profile, nxt, followups, dnc)
    store.set_state(f"followups:{res.next_day}", json.dumps([f.item.target_id for f in res.followups]))
    res.followups_path = write_followups_md(res.followups, res.followup_skips, out_dir / f"followups_{res.next_day}.md",
                                            res.next_day)
    return res
