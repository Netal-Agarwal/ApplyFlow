def followup_checklist(store, profile, day: date, cap: int, dnc=None):
    """(follow-ups due on `day`, why others aren't) in manual mode (no Gmail records needed)."""
    from applyflow.drafting import load_facts
    from applyflow.followups import due_followups
    from applyflow.outreach import build_items
    items = build_items(store, profile, dnc, day=day)
    return due_followups(store, items, day, profile.outreach["sending"], load_facts(profile), dnc, cap=cap,
                         manual=True)


def write_followups_md(due, why_not: dict, path: Path, day: str) -> Path:
    from applyflow.followups import original_day
    lines = [f"# Follow-ups for {day} ({len(due)})", "",
             "Send each by hand as a **reply in the original thread** (find it in Sent by recipient and subject), "
             "with **no attachment**. Keep the subject Gmail gives the reply (Re: <original subject>).", ""]
    if why_not:
        lines.append("Not due / not eligible: " + ", ".join(f"{k} {v}" for k, v in sorted(why_not.items())))
        lines.append("")
    for n, f in enumerate(due, start=1):
        it = f.item
        sent = original_day(f.original, it)
        lines += [f"## {n}. {it.company}", "",
                  f"- Recipient: {it.sent_email}",
                  f"- Original subject: {f.original['subject']}",
                  f"- Original sent: {sent.strftime('%a %d %b %Y') if sent else it.sent_date}",
                  f"- Reply subject: {f.subject}",
                  f"- Variant {f.variant + 1}; target id `{it.target_id}`", "", "```", f.body.rstrip(), "```", ""]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


