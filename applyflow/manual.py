def batch_rows(store, profile, day: str, dnc=None) -> list[dict]:
    """The stored batch for `day`, one dict per row, with anything that breaks the rules in `problems`."""
    from applyflow.drafting import load_facts
    from applyflow.outreach import build_items
    facts = load_facts(profile)
    items = {i.target_id: i for i in build_items(store, profile, dnc)}
    sent_before = {e["email"].split("@")[-1] for e in store.events()
                   if e["event"] == "sent" and (e["batch_date"] or e["event_date"]) != day}
    excluded = store.excluded_contacts()
    out, seen = [], set()
    for r in store.queue(day):
        it = items.get(r["target_id"])
        if it is None:
            out.append({"n": r["position"], "tid": r["target_id"], "problems": ["target no longer exists"]})
            continue
        a, d = it.address, it.draft
        problems = []
        if it.status not in ("ready", "sent"):
            problems.append(f"status {it.status}")
        if a is None or a.email != r["email"]:
            problems.append("address changed since it was queued")
        if it.status == "ready" and r["email"].split("@")[-1] in sent_before:
            problems.append("domain emailed before")
        if r["email"] in excluded or (dnc is not None and dnc.blocks(r["email"])):
            problems.append("excluded / do-not-contact")
        if it.fit_hold:
            problems.append(it.fit_hold)
        if it.company_id in seen:
            problems.append("second row for one company")
        seen.add(it.company_id)
        if d is None or d.source != "claude" or d.failures:
            problems.append(f"no validated Claude draft {d.failures if d else ''}".strip())
        attach = d is not None and d.resume_action == "attach"
        if attach and facts.resume_url and facts.resume_url in d.body:
            problems.append("attaches the PDF and has the Drive link")
        if d is not None and not attach and "attached" in d.body.lower():
            problems.append("Drive-link draft says 'attached'")
        evidence = ""
        if a is not None and a.kind == "evidence_guess":
            ev = a.evidence or {}
            evidence = (f"{ev.get('published', '?')} on {ev.get('published_url', '?')}; "
                        f"{a.name} ({a.role}) on {ev.get('person_url') or a.source_url}")
        out.append({"n": r["position"], "tid": it.target_id, "company": it.company, "sector": it.sector,
                    "size": it.team_size, "contact": f"{a.name} ({a.role})" if a and a.name else (a.role if a else ""),
                    "email": r["email"], "kind": a.kind if a else "", "rg": "role" if it.kind == "role" else "general",
                    "role": it.inputs.role_title if it.kind == "role" else "", "attach": attach, "large": it.large,
                    "subject": d.subject if d else "", "body": d.body if d else "", "evidence": evidence,
                    "problems": problems})
    return out


def write_batch_md(rows: list[dict], path: Path, day: str) -> Path:
    from collections import Counter
    good = [o for o in rows if "company" in o]
    lines = ["| # | Company | Sector | Size | Contact | Email | Type | Email kind | Attach PDF? | Subject |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    for o in good:
        kind = f"role: {o['role']}" if o["rg"] == "role" else "general"
        lines.append(f"| {o['n']} | {o['company']} | {o['sector']} | {o['size'] if o['size'] is not None else '?'} | "
                     f"{o['contact']} | {o['email']} | {KIND_LABELS.get(o['kind'], o['kind'])} | {kind} | "
                     f"{'yes' if o['attach'] else 'no'} | {o['subject']} |")
    evid = [o for o in good if o["evidence"]]
    lines += ["", f"By type: {dict(Counter(KIND_LABELS.get(o['kind'], o['kind']) for o in good))}",
              f"By sector: {dict(Counter(o['sector'] for o in good))}",
              f"Role / general: {dict(Counter(o['rg'] for o in good))}; over 300 people (hiring inbox only): "
              f"{sum(o['large'] for o in good)}",
              f"Attach PDF: {sum(o['attach'] for o in good)} yes, {sum(not o['attach'] for o in good)} no",
              f"Rows with problems: {sum(bool(o['problems']) for o in rows)}"]
    for o in rows:
        if o["problems"]:
            lines.append(f"  - {o.get('company', o['tid'])}: {'; '.join(o['problems'])}")
    if evid:
        lines += ["", "Evidence behind each guess (published address and where; the person and where):"]
        lines += [f"  - {o['company']} -> {o['email']}: {o['evidence']}" for o in evid]
    lines += ["", f"Sent by hand: schedule in Gmail, attach the PDF where 'Attach PDF?' is yes, then "
                  f"`daily --sent {day}` in the evening.", ""]
    for o in good:
        lines += [f"---- {o['company']} ({o['tid']}) -> {o['email']} [{'attach' if o['attach'] else 'link'}]",
                  f"Subject: {o['subject']}", "", o["body"].rstrip(), ""]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


