"""Manual sending (decided 2026-11-02): you schedule each batch yourself in Gmail; ApplyFlow picks it, writes it up
and records what went out. The Phase 3 engine (plan / send / reconcile / check-inbox) stays in the code, unused.

`daily --sent D` is the evening routine, after you've recorded the day's replies and bounces:
  1. backs up the database (data/applyflow.pre-daily-<D>.db)
  2. marks D's stored batch sent (rows you didn't send: --skip <target id>) and D's follow-up checklist as sent
     follow-ups (`followup` events; --skip-followup <target id>)
  3. checks the all-type daily brake on D (`sending.day_brake`: 4+ hard bounces, or more than 12% of D's sends);
     tripped -> stops before building the next batch (--force builds anyway)
  4. builds the next working day's batch with `queue` (freshness check on), and writes output/batch_<next>.md
  5. writes output/followups_<next>.md: follow-ups due that day (5+ working days after the original, oldest first,
     at most --followups), to send by hand as replies in the original thread, with no attachment
The HTML report is regenerated by the CLI afterwards.
"""

from __future__ import annotations

import json
import sqlite3
from dataclasses import dataclass, field
from datetime import date
from pathlib import Path
from typing import Callable

from applyflow import config

Log = Callable[[str], None]
KIND_LABELS = {"hiring_inbox": "hiring inbox", "verified_person": "verified named person", "founders": "founders@",
               "evidence_guess": "evidence guess", "general_inbox": "hello@"}


def backup(store, path: Path) -> Path:
    """A consistent copy of the open database (SQLite backup API)."""
    path.parent.mkdir(parents=True, exist_ok=True)
    dest = sqlite3.connect(str(path))
    with dest:
        store.conn.backup(dest)
    dest.close()
    return path


